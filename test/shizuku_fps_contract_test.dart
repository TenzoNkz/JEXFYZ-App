    expect(floating, contains("'shizuku_bind_exception'"));
    expect(floating, contains("'shizuku_userservice_timeout'"));
    expect(floating, contains("'shizuku_userservice_dead'"));
    expect(floating, isNot(contains('adb shell pm grant')));
    expect(floating, isNot(contains('adb shell pm revoke')));
    expect(floating, isNot(contains('WirelessAdbPairingBridge')));
    expect(settings, contains("'shizukuNotRunning'"));
    expect(settings, contains("'requestShizukuPermission'"));
    expect(settings, isNot(contains('pairWirelessAdb')));
    expect(settings, isNot(contains('copyAdbCommand')));
    expect(service, contains('Shizuku.checkSelfPermission()'));
    expect(service, contains('Shizuku.bindUserService(currentAttempt.args, currentAttempt.connection)'));
    expect(service, contains('private enum class FpsBindingState'));
    expect(service, contains('CountDownLatch(1)'));
    expect(service, contains('currentFpsUserServiceBinding === attempt'));
    expect(service, contains(r'.tag("jex_fps_service_v1_$suffix")'));
